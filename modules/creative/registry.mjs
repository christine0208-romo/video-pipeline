import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { readJson } from "../lib/fsx.mjs";

const toImport = (from, file) => {
  const relative = path
    .relative(from, file)
    .split(path.sep)
    .join("/")
    .replace(/\.tsx?$/, "");
  return relative.startsWith(".") ? relative : `./${relative}`;
};

const toFileImport = (from, file) =>
  `./${path.relative(from, file).split(path.sep).join("/")}`;

export function listEnginePackages(cfg) {
  const root = cfg.paths.creative;
  if (!existsSync(root)) return [];
  const packages = [];
  const enginesDir = path.join(root, "engines");

  if (existsSync(enginesDir)) {
    for (const entry of readdirSync(enginesDir, { withFileTypes: true })) {
      if (!entry.isDirectory()) continue;
      const dir = path.join(enginesDir, entry.name);
      const metaFile = path.join(dir, "engine.json");
      const componentFile = path.join(dir, "index.tsx");
      if (!existsSync(metaFile) || !existsSync(componentFile)) continue;
      const meta = readJson(metaFile, null);
      if (!meta) continue;
      packages.push({
        key: meta.preset ?? entry.name,
        id: meta.id ?? entry.name,
        scope: "shared",
        meta,
        metaFile,
        componentFile,
        importPath: toImport(root, componentFile),
      });
    }
  }

  for (const entry of readdirSync(root, { withFileTypes: true })) {
    if (!entry.isDirectory() || entry.name === "engines") continue;
    const dir = path.join(root, entry.name);
    const metaFile = path.join(dir, "engine", "engine.json");
    const componentFile = path.join(dir, "engine", "index.tsx");
    if (!existsSync(metaFile) || !existsSync(componentFile)) continue;
    const meta = readJson(metaFile, null);
    if (!meta) continue;
    packages.push({
      key: meta.preset ?? entry.name,
      id: meta.id ?? entry.name,
      scope: "local",
      meta,
      metaFile,
      componentFile,
      importPath: toImport(root, componentFile),
    });
  }

  const seen = new Map();
  for (const item of packages) {
    if (seen.has(item.key)) {
      throw new Error(
        `引擎注册键重复：${item.key}（${seen.get(item.key)} / ${item.importPath}）`,
      );
    }
    seen.set(item.key, item.importPath);
  }
  return packages.sort((a, b) => a.key.localeCompare(b.key));
}

export function generateRegistry(cfg) {
  const packages = listEnginePackages(cfg);
  const lines = [
    "// AUTO-GENERATED by `node run.mjs creative scan --write-registry`.",
    "// 不要手改；新增或移动引擎后重新生成。",
    'import type { EngineProps, PresetMeta } from "../src/types";',
    'import type React from "react";',
  ];

  packages.forEach((item, index) => {
    lines.push(
      `import { Component as Component${index} } from "${item.importPath}";`,
    );
    lines.push(
      `import meta${index} from "${toFileImport(path.dirname(path.join(cfg.paths.creative, "registry.ts")), item.metaFile)}";`,
    );
  });

  lines.push("");
  lines.push(
    "const metaOf = (meta: Record<string, unknown>, preset: string): PresetMeta => ({",
    '  id: preset,',
    "  supportsAlpha: Boolean(meta.alpha),",
    "  description: String(meta.label ?? preset),",
    "  category: meta.category,",
    "  loop: Boolean(meta.loop),",
    "  complete: meta.complete,",
    "});",
    "",
  );

  if (!packages.length) {
    lines.push(
      "export const PRESETS: Record<string, { meta: PresetMeta; Component: React.FC<EngineProps> }> = {};",
    );
  } else {
    lines.push(
      "export const PRESETS: Record<string, { meta: PresetMeta; Component: React.FC<EngineProps> }> = {",
    );
    packages.forEach((item, index) => {
      lines.push(
        `  ${JSON.stringify(item.key)}: { meta: metaOf(meta${index} as Record<string, unknown>, ${JSON.stringify(item.key)}), Component: Component${index} as React.FC<EngineProps> },`,
      );
    });
    lines.push("};");
  }

  lines.push("");
  lines.push("export const PRESET_META = Object.values(PRESETS).map((entry) => entry.meta);");
  lines.push("export const PRESET_IDS = Object.keys(PRESETS);");
  lines.push("");
  lines.push(
    "export type FontSpec = { family: string; file: string; weight?: string; style?: string; stretch?: string };",
  );
  const registryFile = path.join(cfg.paths.creative, "registry.ts");
  const fontsFile = path.join(cfg.paths.shared, "fonts.ts");
  if (existsSync(fontsFile)) {
    lines.push(
      `export { FONT_MANIFEST } from "${toImport(path.dirname(registryFile), fontsFile)}";`,
    );
  } else {
    lines.push("export const FONT_MANIFEST: FontSpec[] = [];");
  }
  lines.push("");
  return lines.join("\n");
}

export function writeRegistry(cfg) {
  const file = path.join(cfg.paths.creative, "registry.ts");
  const content = generateRegistry(cfg);
  mkdirSync(path.dirname(file), { recursive: true });
  writeFileSync(file, content);
  return file;
}

export function registryStatus(cfg) {
  const file = path.join(cfg.paths.creative, "registry.ts");
  const expected = generateRegistry(cfg);
  if (!existsSync(file)) return { ok: false, reason: "缺少 creative/registry.ts" };
  const actual = readFileSync(file, "utf8");
  return {
    ok: actual === expected,
    reason: actual === expected ? "" : "注册表已过期",
  };
}
