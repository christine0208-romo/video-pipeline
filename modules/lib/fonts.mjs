import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const FONT_EXT = /\.(otf|ttf|woff2?)$/i;

/** 素材清单里字体条目的 kind；历史数据两种写法都有。 */
export const FONT_KINDS = new Set(["font", "fonts"]);

export const isFontEntry = (entry) =>
  FONT_KINDS.has(entry?.kind) || FONT_EXT.test(entry?.path ?? "");

const WEIGHTS = {
  thin: 100,
  hairline: 100,
  extralight: 200,
  ultralight: 200,
  light: 300,
  regular: 400,
  normal: 400,
  book: 400,
  medium: 500,
  semibold: 600,
  demibold: 600,
  bold: 700,
  extrabold: 800,
  ultrabold: 800,
  black: 900,
  heavy: 900,
};

const STYLES = { italic: "italic", oblique: "oblique" };

function familyFromTokens(tokens) {
  return tokens
    .map((token) => token.replace(/([a-z0-9])([A-Z])/g, "$1 $2"))
    .join(" ")
    .split(/\s+/)
    .filter(Boolean)
    .map((word) =>
      /^[a-z]/.test(word) ? word[0].toUpperCase() + word.slice(1) : word,
    )
    .join(" ");
}

/** 按文件名推断 family/weight；推断不出时 family=文件名词干、weight=400。 */
export function inferFontMeta(relative) {
  const base = path.basename(String(relative)).replace(FONT_EXT, "");
  const tokens = base.split(/[-_.\s]+/).filter(Boolean);
  let weight = null;
  let style = null;
  const familyTokens = [];
  for (const token of tokens) {
    const lower = token.toLowerCase();
    if (/^[1-9]00$/.test(lower)) {
      weight ??= lower;
      continue;
    }
    if (WEIGHTS[lower]) {
      weight ??= String(WEIGHTS[lower]);
      continue;
    }
    if (STYLES[lower]) {
      style ??= STYLES[lower];
      continue;
    }
    familyTokens.push(token);
  }
  const family = familyTokens.length ? familyFromTokens(familyTokens) : base;
  return {
    family: family || base,
    weight: weight ?? "400",
    ...(style ? { style } : {}),
  };
}

/** 给清单里的字体条目补齐缺失的 family/weight/style；返回是否有变更。 */
export function ensureFontMeta(manifest) {
  let changed = false;
  for (const entry of manifest?.assets ?? []) {
    if (!isFontEntry(entry)) continue;
    const inferred = inferFontMeta(entry.path);
    if (!entry.family) {
      entry.family = inferred.family;
      changed = true;
    }
    if (!entry.weight) {
      entry.weight = inferred.weight;
      changed = true;
    }
    if (!entry.style && inferred.style) {
      entry.style = inferred.style;
      changed = true;
    }
  }
  return changed;
}

export function fontEntries(manifest) {
  return (manifest?.assets ?? []).filter(isFontEntry);
}

/** 生成 shared/fonts.ts 内容；file 相对 public/。 */
export function renderFontsTs(manifest) {
  const fonts = fontEntries(manifest)
    .slice()
    .sort((a, b) => a.path.localeCompare(b.path));
  const lines = [
    "// GENERATED by `node run.mjs shared fonts --write`.",
    "// 不要手改；family/weight 在 shared/assets.manifest.json，改元数据用 assets font set。",
    'import type { FontSpec } from "../common/engine";',
    "",
    "export const FONT_MANIFEST: FontSpec[] = [",
  ];
  for (const entry of fonts) {
    const fields = [
      `family: ${JSON.stringify(entry.family)}`,
      `file: ${JSON.stringify(`assets/${entry.path}`)}`,
      `weight: ${JSON.stringify(String(entry.weight))}`,
    ];
    if (entry.style) fields.push(`style: ${JSON.stringify(entry.style)}`);
    lines.push(`  { ${fields.join(", ")} },`);
  }
  lines.push("];", "");
  return lines.join("\n");
}

export function fontsFile(cfg) {
  return path.join(cfg.paths.shared, "fonts.ts");
}

/**
 * 写 shared/fonts.ts。write=false 时只算内容，不改文件。
 * 返回 { file, text, changed, written, entries }。
 */
export function writeFontsTs(cfg, manifest, { write = false } = {}) {
  const entries = fontEntries(manifest).length;
  const text = renderFontsTs(manifest);
  const file = fontsFile(cfg);
  const previous = existsSync(file) ? readFileSync(file, "utf8") : null;
  const changed = previous !== text;
  const written = write && changed;
  if (written) {
    mkdirSync(path.dirname(file), { recursive: true });
    writeFileSync(file, text);
  }
  return { file, text, changed, written, entries };
}
